-- Restaurant core schema (AGENTS.md section 5).
-- Every table carries the publish-service BasePrimaryIdEntity columns
-- (id, created_at, created_by, modified_at, modified_by, is_activate, audit_remark).
-- created_by is that inherited audit string, so user foreign keys use explicit names (e.g. created_by_user_id).
-- Business event timestamps are TIMESTAMPTZ; money is NUMERIC(12,2).

-- ---------------------------------------------------------------------------
-- Users: extend the existing app_user instead of creating a second user table.
-- ---------------------------------------------------------------------------
ALTER TABLE app_user
    ADD COLUMN full_name VARCHAR(150) NOT NULL,
    ADD COLUMN role      VARCHAR(30)  NOT NULL,
    ADD CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'CASHIER', 'WAITER', 'KITCHEN'));

-- ---------------------------------------------------------------------------
-- Menu
-- ---------------------------------------------------------------------------
CREATE TABLE menu_categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    created_by   VARCHAR(255),
    modified_at  TIMESTAMP(6),
    modified_by  VARCHAR(255),
    is_activate  BOOLEAN,
    audit_remark VARCHAR(255),
    name         VARCHAR(100) NOT NULL,
    description  TEXT
);

CREATE TABLE menu_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    created_by   VARCHAR(255),
    modified_at  TIMESTAMP(6),
    modified_by  VARCHAR(255),
    is_activate  BOOLEAN,
    audit_remark VARCHAR(255),
    category_id  BIGINT         NOT NULL REFERENCES menu_categories (id),
    name         VARCHAR(150)   NOT NULL,
    description  TEXT,
    price        NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    image_url    TEXT,
    is_available BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE INDEX ix_menu_items_category_id ON menu_items (category_id);

-- ---------------------------------------------------------------------------
-- Restaurant tables
-- ---------------------------------------------------------------------------
CREATE TABLE restaurant_tables (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    created_by   VARCHAR(255),
    modified_at  TIMESTAMP(6),
    modified_by  VARCHAR(255),
    is_activate  BOOLEAN,
    audit_remark VARCHAR(255),
    table_number VARCHAR(20) NOT NULL,
    capacity     INTEGER     NOT NULL CHECK (capacity > 0),
    status       VARCHAR(20) NOT NULL,
    CONSTRAINT uk_restaurant_tables_table_number UNIQUE (table_number),
    CONSTRAINT ck_restaurant_tables_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'RESERVED', 'OUT_OF_SERVICE'))
);

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------
CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6),
    created_by         VARCHAR(255),
    modified_at        TIMESTAMP(6),
    modified_by        VARCHAR(255),
    is_activate        BOOLEAN,
    audit_remark       VARCHAR(255),
    version            BIGINT         NOT NULL DEFAULT 0,
    order_number       VARCHAR(40)    NOT NULL,
    table_id           BIGINT REFERENCES restaurant_tables (id),
    created_by_user_id BIGINT         NOT NULL REFERENCES app_user (id),
    order_type         VARCHAR(20)    NOT NULL,
    order_status       VARCHAR(30)    NOT NULL,
    payment_status     VARCHAR(30)    NOT NULL,
    subtotal           NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    discount_amount    NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount         NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    total_amount       NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
    notes              TEXT,
    completed_at       TIMESTAMPTZ,
    cancelled_at       TIMESTAMPTZ,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    CONSTRAINT ck_orders_order_type CHECK (order_type IN ('DINE_IN', 'TAKEAWAY', 'DELIVERY')),
    CONSTRAINT ck_orders_order_status CHECK (order_status IN
        ('PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'SERVED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment_status CHECK (payment_status IN
        ('UNPAID', 'PARTIALLY_PAID', 'PAID', 'PARTIALLY_REFUNDED', 'REFUNDED'))
);

CREATE INDEX ix_orders_created_at ON orders (created_at);
CREATE INDEX ix_orders_order_status ON orders (order_status);
CREATE INDEX ix_orders_payment_status ON orders (payment_status);
CREATE INDEX ix_orders_table_id ON orders (table_id);
CREATE INDEX ix_orders_created_by_user_id ON orders (created_by_user_id);

CREATE TABLE order_items (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           TIMESTAMP(6),
    created_by           VARCHAR(255),
    modified_at          TIMESTAMP(6),
    modified_by          VARCHAR(255),
    is_activate          BOOLEAN,
    audit_remark         VARCHAR(255),
    version              BIGINT         NOT NULL DEFAULT 0,
    order_id             BIGINT         NOT NULL REFERENCES orders (id),
    menu_item_id         BIGINT REFERENCES menu_items (id),
    item_name            VARCHAR(150)   NOT NULL,
    quantity             INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price           NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    line_total           NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0),
    special_instructions TEXT,
    kitchen_status       VARCHAR(20)    NOT NULL,
    CONSTRAINT ck_order_items_line_total CHECK (line_total = unit_price * quantity),
    CONSTRAINT ck_order_items_kitchen_status CHECK (kitchen_status IN
        ('PENDING', 'PREPARING', 'READY', 'SERVED', 'CANCELLED'))
);

CREATE INDEX ix_order_items_order_id ON order_items (order_id);
CREATE INDEX ix_order_items_menu_item_id ON order_items (menu_item_id);
CREATE INDEX ix_order_items_kitchen_status ON order_items (kitchen_status);

-- ---------------------------------------------------------------------------
-- Payments
-- ---------------------------------------------------------------------------
CREATE TABLE payments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at            TIMESTAMP(6),
    created_by            VARCHAR(255),
    modified_at           TIMESTAMP(6),
    modified_by           VARCHAR(255),
    is_activate           BOOLEAN,
    audit_remark          VARCHAR(255),
    version               BIGINT         NOT NULL DEFAULT 0,
    order_id              BIGINT         NOT NULL REFERENCES orders (id),
    amount                NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    payment_method        VARCHAR(20)    NOT NULL,
    payment_status        VARCHAR(20)    NOT NULL,
    transaction_reference VARCHAR(150),
    received_by           BIGINT REFERENCES app_user (id),
    paid_at               TIMESTAMPTZ,
    CONSTRAINT ck_payments_payment_method CHECK (payment_method IN ('CASH', 'CARD', 'QR', 'OTHER')),
    CONSTRAINT ck_payments_payment_status CHECK (payment_status IN ('PENDING', 'COMPLETED', 'FAILED', 'REVERSED'))
);

CREATE INDEX ix_payments_order_id ON payments (order_id);
CREATE INDEX ix_payments_paid_at ON payments (paid_at);
CREATE INDEX ix_payments_received_by ON payments (received_by);

-- ---------------------------------------------------------------------------
-- Status history (append-only audit)
-- ---------------------------------------------------------------------------
CREATE TABLE order_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    created_by   VARCHAR(255),
    modified_at  TIMESTAMP(6),
    modified_by  VARCHAR(255),
    is_activate  BOOLEAN,
    audit_remark VARCHAR(255),
    order_id     BIGINT      NOT NULL REFERENCES orders (id),
    old_status   VARCHAR(30),
    new_status   VARCHAR(30) NOT NULL,
    changed_by   BIGINT REFERENCES app_user (id),
    changed_at   TIMESTAMPTZ NOT NULL,
    note         TEXT,
    CONSTRAINT ck_order_status_history_old_status CHECK (old_status IN
        ('PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'SERVED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_order_status_history_new_status CHECK (new_status IN
        ('PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'SERVED', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX ix_order_status_history_order_id ON order_status_history (order_id);
CREATE INDEX ix_order_status_history_changed_by ON order_status_history (changed_by);

CREATE TABLE order_item_status_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6),
    created_by    VARCHAR(255),
    modified_at   TIMESTAMP(6),
    modified_by   VARCHAR(255),
    is_activate   BOOLEAN,
    audit_remark  VARCHAR(255),
    order_item_id BIGINT      NOT NULL REFERENCES order_items (id),
    old_status    VARCHAR(20),
    new_status    VARCHAR(20) NOT NULL,
    changed_by    BIGINT REFERENCES app_user (id),
    changed_at    TIMESTAMPTZ NOT NULL,
    note          TEXT,
    CONSTRAINT ck_order_item_status_history_old_status CHECK (old_status IN
        ('PENDING', 'PREPARING', 'READY', 'SERVED', 'CANCELLED')),
    CONSTRAINT ck_order_item_status_history_new_status CHECK (new_status IN
        ('PENDING', 'PREPARING', 'READY', 'SERVED', 'CANCELLED'))
);

CREATE INDEX ix_order_item_status_history_order_item_id ON order_item_status_history (order_item_id);
CREATE INDEX ix_order_item_status_history_changed_by ON order_item_status_history (changed_by);
